CREATE TABLE dbo.categories (
    id int IDENTITY(1,1) NOT NULL,
    name nvarchar(100) COLLATE Latin1_General_100_CI_AS NOT NULL,
    CONSTRAINT PK_categories PRIMARY KEY (id),
    CONSTRAINT UQ_categories_name UNIQUE (name),
    CONSTRAINT CK_categories_name CHECK (LEN(LTRIM(RTRIM(name))) > 0)
);
CREATE TABLE dbo.brands (
    id int IDENTITY(1,1) NOT NULL,
    name nvarchar(100) COLLATE Latin1_General_100_CI_AS NOT NULL,
    CONSTRAINT PK_brands PRIMARY KEY (id),
    CONSTRAINT UQ_brands_name UNIQUE (name),
    CONSTRAINT CK_brands_name CHECK (LEN(LTRIM(RTRIM(name))) > 0)
);
CREATE TABLE dbo.tags (
    id int IDENTITY(1,1) NOT NULL,
    name nvarchar(100) COLLATE Latin1_General_100_CI_AS NOT NULL,
    CONSTRAINT PK_tags PRIMARY KEY (id),
    CONSTRAINT UQ_tags_name UNIQUE (name),
    CONSTRAINT CK_tags_name CHECK (LEN(LTRIM(RTRIM(name))) > 0)
);
CREATE TABLE dbo.products (
    id int IDENTITY(1,1) NOT NULL,
    name nvarchar(200) NOT NULL,
    description nvarchar(2000) NOT NULL,
    price decimal(18,2) NOT NULL,
    stock int NOT NULL,
    rating decimal(2,1) NOT NULL,
    created_at date NOT NULL,
    category_id int NOT NULL,
    brand_id int NOT NULL,
    CONSTRAINT PK_products PRIMARY KEY (id),
    CONSTRAINT CK_products_name CHECK (LEN(LTRIM(RTRIM(name))) > 0),
    CONSTRAINT CK_products_description CHECK (LEN(LTRIM(RTRIM(description))) > 0),
    CONSTRAINT CK_products_price CHECK (price >= 0),
    CONSTRAINT CK_products_stock CHECK (stock >= 0),
    CONSTRAINT CK_products_rating CHECK (rating >= 0 AND rating <= 5),
    CONSTRAINT FK_products_categories FOREIGN KEY (category_id) REFERENCES dbo.categories(id),
    CONSTRAINT FK_products_brands FOREIGN KEY (brand_id) REFERENCES dbo.brands(id)
);
CREATE INDEX IX_products_category_id ON dbo.products(category_id);
CREATE INDEX IX_products_brand_id ON dbo.products(brand_id);
CREATE TABLE dbo.product_tags (
    product_id int NOT NULL,
    tag_id int NOT NULL,
    CONSTRAINT PK_product_tags PRIMARY KEY (product_id, tag_id),
    CONSTRAINT FK_product_tags_products FOREIGN KEY (product_id) REFERENCES dbo.products(id) ON DELETE CASCADE,
    CONSTRAINT FK_product_tags_tags FOREIGN KEY (tag_id) REFERENCES dbo.tags(id) ON DELETE CASCADE
);
CREATE INDEX IX_product_tags_tag_id ON dbo.product_tags(tag_id);
